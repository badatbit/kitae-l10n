def _fw_inner(s):
    """낱말 사이 반각 공백만 전각으로. 앞뒤 정렬용 공백은 그대로 둔다."""
    lead = len(s) - len(s.lstrip(" "))
    tail = len(s) - len(s.rstrip(" "))
    body = s[lead:len(s) - tail] if tail else s[lead:]
    return s[:lead] + body.replace(" ", "　") + (s[len(s) - tail:] if tail else "")


class Ctr(str):
    """가운데 맞춤 표시. 폭은 **원문에서 가져온다** — 손으로 적으면 틀린다."""


class Raw(str):
    """공백을 손대지 말 것. 쪽 번호처럼 반각으로 자릿수를 맞춘 항목에 쓴다."""


def pad(left, right, ja):
    """`이름 ……… 1/4` 처럼 좌우로 벌려 원문과 같은 폭을 만든다."""
    n = width(ja) - width(left) - width(right)
    return Raw(left + " " * max(1, n) + right)


def ctr(text):
    return Ctr(text)


def width(s):
    return sum(1 if ord(c) < 0x80 else 2 for c in s)


def center_to(text, ja):
    """원문과 같은 반각 폭이 되도록 좌우를 반각 공백으로 채운다."""
    text = _fw_inner(text.strip())
    pad = max(0, width(ja) - width(text))
    return " " * (pad // 2) + text + " " * (pad - pad // 2)


