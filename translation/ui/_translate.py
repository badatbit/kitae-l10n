def blen(s):
    """게임 바이트 수. 한글·전각 2바이트, 반각 1바이트."""
    return sum(1 if ord(c) < 0x80 and c != "\n" else
               (1 if c == "\n" else 2) for c in s)


def fullwidth(s):
    """낱말 사이 반각 공백을 전각으로. **앞뒤 정렬용 공백은 그대로 둔다.**

    UI 원문은 전부 전각이라 모든 글자가 짝수 바이트 위치에 온다. 반각을 끼우면
    그 뒤가 홀수로 밀리는데, 엔진이 고정 바이트 위치에 값을 써 넣는 자리(포트
    문자, 소켓 번호, 날짜)에서 한글 한 글자의 가운데를 덮어써 깨진다.

    앞뒤 공백은 타이틀·미니게임 목록의 가운데 맞춤에 쓰이는 반각이라 건드리면
    줄이 어긋난다.
    """
    return _fw_inner(s)


