def cells(t):
    return sum(0.5 if len(c.encode("cp932", "replace")) == 1 else 1 for c in t)


def main():
    with io.open(os.path.join(GUIDE, "guides.json"), encoding="utf-8") as fh:
        src = json.load(fh)
    by = {(e["window"], e["line"]): e for e in src["entries"]}

    bad, table = [], {}
    for k, ko in KO.items():
        e = by.get(k)
        if e is None:
            bad.append(f"{k}: 그런 자리가 없다")
            continue
        if cells(ko) > MAX:
            bad.append(f"{k}: {cells(ko)}칸 > {MAX}  {ko}")
        table[e["text"]["ja"]] = ko
    if bad:
        print(f"검사 실패 {len(bad)}건")
        for b in bad:
            print("  " + b)
        return 1

    n = 0
    for f in ("guide.json", "guide2.json", "guides.json"):
        p = os.path.join(GUIDE, f)
        with io.open(p, encoding="utf-8") as fh:
            doc = json.load(fh)
        for e in doc["entries"]:
            ja = e["text"]["ja"]
            if ja in table and not (e["text"].get("ko") or "").strip():
                e["text"]["ko"] = table[ja]
                n += 1
        if f == "guides.json":
            b2 = {(x["window"], x["line"]): x for x in doc["entries"]}
            for k, why in ASK.items():
                if k in b2:
                    b2[k]["ask"] = [{"why": why, "state": "open"}]
        with io.open(p, "w", encoding="utf-8") as fh:
            fh.write(json.dumps(doc, ensure_ascii=False, indent=2) + "\n")

    tot = done = 0
    for f in ("guide.json", "guide2.json", "guides.json"):
        with io.open(os.path.join(GUIDE, f), encoding="utf-8") as fh:
            doc = json.load(fh)
        tot += len(doc["entries"])
        done += sum(1 for e in doc["entries"] if (e["text"].get("ko") or "").strip())
    print(f"검사 통과 — 문장 {len(table)}개로 {n}줄 채움. "
          f"관광지 {done}/{tot}줄 ({done*100//tot}%), 검토 요청 {len(ASK)}건")
    return 0


if __name__ == "__main__":
    sys.exit(main())
