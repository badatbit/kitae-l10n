def gbytes(s):
    """게임 인코딩에서 차지할 바이트. 한글은 예외 없이 ２바이트다.

    `hangul.encoder` 로 재면 **아직 코드페이지에 없는 글자에서 죽는다** —
    새 글자는 빌드가 폰트에 넣으면서 그때 배정하기 때문이다. 자리 검사에
    인코더를 쓰면 안 된다.
    """
    n = 0
    for c in MARKUP.sub("", s or ""):
        if c == "\n":
            n += 1
            continue
        try:
            n += len(c.encode("cp932"))
        except UnicodeEncodeError:
            n += 2
    return n


def cells(s):
    return max((sum(0.5 if len(c.encode("cp932", "replace")) == 1 else 1
                    for c in MARKUP.sub("", x))
                for x in (s or "").split("\n")), default=0)


def main():
    bad, n = [], 0
    for mod, rows in KO.items():
        p = os.path.join(UI, mod + ".json")
        doc = json.load(io.open(p, encoding="utf-8"))
        by = {e.get("offset"): e for e in doc["entries"]}
        for off, ko in rows.items():
            e = by.get(off)
            if e is None:
                bad.append(f"{mod} @{off}: 그런 자리가 없다")
                continue
            av = e.get("avail") or len(e["text"]["ja"].encode("cp932", "replace"))
            b = gbytes(ko)
            if b > av:
                bad.append(f"{mod} @{off}: {b}B > 자리 {av}B  {ko[:28]!r}")
            if cells(ko) > MAX:
                bad.append(f"{mod} @{off}: {cells(ko)}칸 > {MAX}  {ko[:28]!r}")
            if sorted(MARKUP.findall(e["text"]["ja"])) != sorted(MARKUP.findall(ko)):
                bad.append(f"{mod} @{off}: 마크업 불일치")
        if not bad:
            for off, ko in rows.items():
                by[off]["text"]["ko"] = ko
                n += 1
            for (m, o), why in ASK.items():
                if m == mod and o in by:
                    by[o]["ask"] = [{"why": why, "state": "open"}]
            io.open(p, "w", encoding="utf-8").write(
                json.dumps(doc, ensure_ascii=False, indent=2) + "\n")
    if bad:
        print(f"검사 실패 {len(bad)}건")
        for b in bad:
            print("  " + b)
        return 1
    print(f"검사 통과 — 미니게임 {len(KO)}개 모듈 {n}줄 기록, 검토 요청 {len(ASK)}건")
    return 0


