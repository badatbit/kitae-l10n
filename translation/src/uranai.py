def cells(s):
    return len(MARKUP.sub("", s))


def halfwidth(s):
    out = []
    for c in MARKUP.sub("", s):
        try:
            if len(c.encode("cp932")) == 1:
                out.append(c)
        except UnicodeEncodeError:
            pass
    return out


