def cells(s):
    n = 0.0
    for c in MARKUP.sub("", s or ""):
        try:
            n += 0.5 if len(c.encode("cp932")) == 1 else 1
        except UnicodeEncodeError:
            n += 1
    return n


def halfwidth(s):
    out = []
    for c in MARKUP.sub("", s or ""):
        try:
            if len(c.encode("cp932")) == 1:
                out.append(c)
        except UnicodeEncodeError:
            pass
    return out


